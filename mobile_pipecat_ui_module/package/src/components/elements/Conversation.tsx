import { usePipecatConversation } from "@/hooks/usePipecatConversation";
import { cn } from "@/lib/utils";
import { usePipecatClientTransportState } from "@pipecat-ai/client-react";
import { TextMode } from "@/types/conversation";
import { memo, useCallback, useEffect, useMemo, useRef } from "react";
import { MessageContainer } from "./MessageContainer";

/**
 * Props for the Conversation component
 */
export interface ConversationProps {
  /**
   * Custom CSS classes for different parts of the component
   */
  classNames?: {
    /** CSS classes for the main container */
    container?: string;
    /** CSS classes for individual message containers */
    message?: string;
    /** CSS classes for message content area */
    messageContent?: string;
    /** CSS classes for role labels */
    role?: string;
    /** CSS classes for timestamp elements */
    time?: string;
    /** CSS classes for thinking indicator */
    thinking?: string;
  };
  /**
   * Disable automatic scrolling to bottom when new messages arrive
   * @default false
   */
  noAutoscroll?: boolean;
  /**
   * After the user scrolls up, wait at least this many milliseconds before
   * allowing auto-scroll to bottom again. Only applies when noAutoscroll is false.
   * @default 10000
   */
  autoscrollResumeDelayMs?: number;
  /**
   * Custom label for assistant messages
   * @default "assistant"
   */
  assistantLabel?: string;
  /**
   * Custom label for user/client messages
   * @default "user"
   */
  clientLabel?: string;
  /**
   * Display name for the primary (non-diarized) user.
   * If Soniox diarization detects multiple speakers, the UI will prefer "user_1", "user_2", ...
   */
  clientDisplayName?: string;
  /**
   * Custom label for system messages
   * @default "system"
   */
  systemLabel?: string;
  /**
   * Text mode for displaying assistant messages.
   * - "llm": Shows text as it's generated by the LLM
   * - "tts": Shows text as it's spoken by the TTS
   * @default "llm"
   */
  textMode?: TextMode;
  /**
   * Whether to render text as markdown.
   * When enabled, markdown syntax in message text will be rendered as formatted content.
   * @default true
   */
  enableMarkdown?: boolean;
  /**
   * Optional content pinned to the very top of the scroll container, above
   * the message list. It scrolls away with the conversation as messages
   * accumulate. When provided, the scrollable shell is always rendered (the
   * "connecting"/"not connected"/"waiting" placeholders are suppressed) so
   * the slot stays visible as a home screen until the first message arrives.
   */
  headerSlot?: React.ReactNode;
}

/**
 * Conversation component that displays real-time conversation history between users and AI assistants.
 *
 * This component automatically integrates with the Pipecat Client SDK to show messages,
 * connection states, and provides smooth scrolling behavior. It must be used within
 * a PipecatClientProvider and ConversationProvider context.
 *
 * @example
 * ```tsx
 * import { Conversation } from "@pipecat-ai/voice-ui-kit";
 *
 * <div className="h-96 border rounded-lg">
 *   <Conversation
 *     assistantLabel="AI Assistant"
 *     clientLabel="You"
 *     noAutoscroll={false}
 *   />
 * </div>
 * ```
 *
 * @param props - The component props
 * @param props.classNames - Custom CSS classes for styling different parts
 * @param props.noAutoscroll - Whether to disable automatic scrolling
 * @param props.autoscrollResumeDelayMs - After user scrolls up, wait this many ms before allowing auto-scroll again (default 10000)
 * @param props.assistantLabel - Custom label for assistant messages
 * @param props.clientLabel - Custom label for user messages
 *
 * @returns A React component that renders the conversation interface
 */
const AUTOSCROLL_RESUME_DELAY_MS = 10_000;

export const Conversation: React.FC<ConversationProps> = memo(
  ({
    assistantLabel,
    classNames = {},
    clientLabel,
    clientDisplayName,
    noAutoscroll = false,
    autoscrollResumeDelayMs = AUTOSCROLL_RESUME_DELAY_MS,
    systemLabel,
    textMode = "llm",
    enableMarkdown = true,
    headerSlot,
  }) => {
    const transportState = usePipecatClientTransportState();

    const scrollRef = useRef<HTMLDivElement>(null);
    const contentRef = useRef<HTMLDivElement>(null);
    const isScrolledToBottom = useRef(true);
    /** When the user scrolled up (left the bottom). Null = auto-scroll allowed. */
    const userScrolledUpAt = useRef<number | null>(null);
    const resumeAutoscrollTimerRef = useRef<ReturnType<
      typeof setTimeout
    > | null>(null);

    /**
     * The maximum scrollTop value we've ever reached. Once we've scrolled
     * down to a position, automatic events (browser scrollTop clamping after
     * content shrinks, layout shifts, etc.) are NOT allowed to drop us below
     * this floor. Only an explicit user gesture (touch/wheel/pointer) is
     * allowed to lower it.
     */
    const scrollTopFloor = useRef(0);
    /**
     * The largest scrollHeight we've ever observed on the inner content
     * container, applied back as min-height. This guarantees the container
     * can actually accommodate scrollTopFloor when shrinking content would
     * otherwise reduce scrollHeight and force the browser to clamp scrollTop
     * downward.
     */
    const maxObservedHeight = useRef(0);
    /**
     * True while the user is actively manipulating the scroll position
     * (touch dragging, wheel scrolling, etc.). While true, the floor is
     * disengaged so the user can scroll freely in any direction.
     */
    const isUserInteracting = useRef(false);
    const userInteractionEndTimer = useRef<ReturnType<
      typeof setTimeout
    > | null>(null);

    /**
     * Scrolls to the bottom only if the user is at the bottom and has not
     * recently scrolled up (or autoscrollResumeDelayMs has passed).
     * Stops auto-scroll when the user scrolls (mouse or touch) until the delay passes.
     */
    const maybeScrollToBottom = useCallback(() => {
      if (!scrollRef.current || noAutoscroll) return;
      if (!isScrolledToBottom.current) return;
      // Don’t auto-scroll until autoscrollResumeDelayMs has passed (timer clears this)
      if (userScrolledUpAt.current != null) return;
      scrollRef.current.scrollTo({
        top: scrollRef.current.scrollHeight,
        behavior: "smooth",
      });
    }, [noAutoscroll]);

    /**
     * Updates the scroll state and user-scroll-up tracking.
     * When the user scrolls away from the bottom (mouse or touch), auto-scroll
     * is paused for autoscrollResumeDelayMs.
     */
    const updateScrollState = useCallback(() => {
      if (!scrollRef.current || noAutoscroll) return;
      const atBottom =
        Math.ceil(
          scrollRef.current.scrollHeight - scrollRef.current.scrollTop,
        ) <= Math.ceil(scrollRef.current.clientHeight);
      isScrolledToBottom.current = atBottom;

      if (atBottom) {
        userScrolledUpAt.current = null;
        if (resumeAutoscrollTimerRef.current) {
          clearTimeout(resumeAutoscrollTimerRef.current);
          resumeAutoscrollTimerRef.current = null;
        }
      } else {
        const now = Date.now();
        if (userScrolledUpAt.current === null) {
          userScrolledUpAt.current = now;
        }
        if (resumeAutoscrollTimerRef.current) {
          clearTimeout(resumeAutoscrollTimerRef.current);
        }
        resumeAutoscrollTimerRef.current = setTimeout(() => {
          resumeAutoscrollTimerRef.current = null;
          userScrolledUpAt.current = null;
        }, autoscrollResumeDelayMs);
      }
    }, [noAutoscroll, autoscrollResumeDelayMs]);

    const { messages } = usePipecatConversation({ textMode });

    const diarization = useMemo(() => {
      const ids: string[] = [];
      for (const m of messages) {
        if (m.role !== "user") continue;
        const id = (m.user_id || "").trim();
        if (!id) continue;
        if (id === "__webview_handoff__") continue;
        ids.push(id);
      }
      const distinct = Array.from(new Set(ids));
      const active = distinct.length >= 2;
      const idToIndex = new Map<string, number>();
      if (active) {
        distinct.forEach((id, idx) => idToIndex.set(id, idx + 1));
      }
      return { active, idToIndex };
    }, [messages]);

    // Determine connection states based on transport state
    const isConnecting =
      transportState === "authenticating" || transportState === "connecting";
    const isConnected =
      transportState === "connected" || transportState === "ready";

    // Auto-scroll when messages change (if enabled)
    useEffect(() => {
      if (noAutoscroll) return;
      // Scroll to bottom when messages change (only if already at bottom)
      maybeScrollToBottom();
    }, [messages, maybeScrollToBottom, noAutoscroll]);

    // Set up scroll event listener to track user scroll position (mouse and touch)
    useEffect(() => {
      const scrollElement = scrollRef.current;
      if (!scrollElement) return;

      const markUserInteracting = () => {
        isUserInteracting.current = true;
        if (userInteractionEndTimer.current) {
          clearTimeout(userInteractionEndTimer.current);
        }
        // Give the scroll a moment to settle after the gesture ends before
        // re-engaging the floor; otherwise momentum scrolling on touch devices
        // would immediately snap back.
        userInteractionEndTimer.current = setTimeout(() => {
          isUserInteracting.current = false;
          // Re-baseline the floor to wherever the user left the viewport so
          // we don't immediately snap them back down.
          if (scrollRef.current) {
            scrollTopFloor.current = scrollRef.current.scrollTop;
          }
        }, 300);
      };

      const handleScroll = () => {
        updateScrollState();

        if (noAutoscroll) return;
        const el = scrollRef.current;
        if (!el) return;
        const st = el.scrollTop;

        if (isUserInteracting.current) {
          // User-driven scroll — let them go anywhere, just track current position
          scrollTopFloor.current = st;
          return;
        }

        // Automatic scroll change (programmatic scroll-to-bottom OR browser
        // clamping after content shrank). Only allow scrollTop to *increase*;
        // any decrease is treated as the unwanted "drop down" and reverted.
        if (st < scrollTopFloor.current) {
          // Try to restore. If scrollHeight currently isn't tall enough, this
          // will be clamped — the min-height lock below is what makes the
          // restoration actually take effect.
          el.scrollTop = scrollTopFloor.current;
        } else if (st > scrollTopFloor.current) {
          scrollTopFloor.current = st;
        }
      };

      scrollElement.addEventListener("scroll", handleScroll, { passive: true });
      scrollElement.addEventListener("wheel", markUserInteracting, {
        passive: true,
      });
      scrollElement.addEventListener("touchstart", markUserInteracting, {
        passive: true,
      });
      scrollElement.addEventListener("touchmove", markUserInteracting, {
        passive: true,
      });
      scrollElement.addEventListener("pointerdown", markUserInteracting, {
        passive: true,
      });

      // Initial check
      updateScrollState();

      return () => {
        scrollElement.removeEventListener("scroll", handleScroll);
        scrollElement.removeEventListener("wheel", markUserInteracting);
        scrollElement.removeEventListener("touchstart", markUserInteracting);
        scrollElement.removeEventListener("touchmove", markUserInteracting);
        scrollElement.removeEventListener("pointerdown", markUserInteracting);
        if (resumeAutoscrollTimerRef.current) {
          clearTimeout(resumeAutoscrollTimerRef.current);
          resumeAutoscrollTimerRef.current = null;
        }
        if (userInteractionEndTimer.current) {
          clearTimeout(userInteractionEndTimer.current);
          userInteractionEndTimer.current = null;
        }
      };
    }, [updateScrollState, noAutoscroll]);

    // Lock the inner container's min-height to the largest height we've ever
    // observed. This prevents scrollHeight from shrinking mid-stream (e.g. when
    // a bubble's markdown content is briefly cleared and re-rendered), which
    // would otherwise force the browser to clamp scrollTop downward — exactly
    // the "drop down" the floor logic is trying to prevent.
    useEffect(() => {
      const target = contentRef.current;
      if (!target || typeof ResizeObserver === "undefined") return;
      const observer = new ResizeObserver(() => {
        const current = target.scrollHeight;
        if (current > maxObservedHeight.current) {
          maxObservedHeight.current = current;
          target.style.minHeight = `${current}px`;
        }
      });
      observer.observe(target);
      return () => observer.disconnect();
    }, []);

    // Reset floor + min-height lock when the conversation is cleared so a new
    // session doesn't start with a giant locked-in empty space.
    useEffect(() => {
      if (messages.length === 0) {
        scrollTopFloor.current = 0;
        maxObservedHeight.current = 0;
        if (contentRef.current) {
          contentRef.current.style.minHeight = "";
        }
      }
    }, [messages.length]);

    const messageList = (
      <div ref={contentRef} className={cn(classNames.message)}>
        {messages.map((message, index) => (
          <MessageContainer
            key={index}
            message={message}
            assistantLabel={assistantLabel}
            clientLabel={clientLabel}
            systemLabel={systemLabel}
            enableMarkdown={enableMarkdown}
            roleLabelOverride={(() => {
              if (message.role !== "user") return undefined;
              const base = clientLabel || "user";
              const rawId = (message.user_id || "").trim();
              if (!rawId || rawId === "__webview_handoff__") return base;
              // Predefined primary user id: show users.name for the main speaker.
              if (rawId === "user_0") {
                if (clientDisplayName && clientDisplayName.trim()) {
                  return clientDisplayName.trim();
                }
                return base;
              }

              if (diarization.active) {
                const idx = diarization.idToIndex.get(rawId) ?? 1;
                return `${base}_${idx}`;
              }

              // Single-speaker: prefer OAuth/display name over raw IDs like "user_anonymous"
              if (clientDisplayName && clientDisplayName.trim()) {
                return clientDisplayName.trim();
              }
              return base;
            })()}
            classNames={{
              container: classNames.message,
              messageContent: classNames.messageContent,
              thinking: classNames.thinking,
              time: classNames.time,
              role: classNames.role,
            }}
          />
        ))}
      </div>
    );

    // Show messages first if they exist, regardless of connection state.
    // A headerSlot also forces the scrollable shell so the slot stays pinned
    // to the top of the scroll (and scrolls away once messages arrive).
    if (headerSlot || messages.length > 0) {
      return (
        <div
          ref={scrollRef}
          className={cn(
            "relative h-full overflow-y-auto p-4",
            classNames.container,
          )}
        >
          {headerSlot}
          {messageList}
        </div>
      );
    }

    // Only show connection states if there are no messages
    if (isConnecting) {
      return (
        <div
          className={cn(
            "relative flex items-center justify-center h-full",
            classNames.container,
          )}
        >
          <div className="text-muted-foreground text-sm">
            Connecting to agent...
          </div>
        </div>
      );
    }

    if (!isConnected) {
      return (
        <div
          className={cn(
            "relative flex items-center justify-center h-full",
            classNames.container,
          )}
        >
          <div className="text-center p-4">
            <div className="text-muted-foreground mb-2">
              Not connected to agent
            </div>
            <p className="text-sm text-muted-foreground max-w-md">
              Connect to an agent to see conversation messages in real-time.
            </p>
          </div>
        </div>
      );
    }

    return (
      <div
        className={cn(
          "relative flex items-center justify-center h-full",
          classNames.container,
        )}
      >
        <div className="text-muted-foreground text-sm">
          Waiting for messages...
        </div>
      </div>
    );
  },
);

/**
 * Default export of the Conversation component
 */
export default Conversation;
